    id UUID PRIMARY KEY DEFAULT gen_random_uuid(), session_id UUID NOT NULL REFERENCES interview_sessions(id),
    event_type VARCHAR(64) NOT NULL, occurred_at TIMESTAMP NOT NULL, metadata TEXT,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL
);
