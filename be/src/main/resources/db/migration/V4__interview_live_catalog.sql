CREATE TABLE interview_roles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(), code VARCHAR(64) NOT NULL UNIQUE,
    label VARCHAR(255) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL
);
CREATE TABLE interview_levels (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(), code VARCHAR(32) NOT NULL UNIQUE,
    label VARCHAR(255) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL
);
CREATE TABLE interview_topics (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(), code VARCHAR(64) NOT NULL UNIQUE,
    label VARCHAR(255) NOT NULL, phase VARCHAR(32) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL
);
CREATE TABLE interview_catalog_rules (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(), role_id UUID NOT NULL REFERENCES interview_roles(id),
    level_id UUID NOT NULL REFERENCES interview_levels(id), topic_id UUID NOT NULL REFERENCES interview_topics(id),
    required BOOLEAN NOT NULL, allow_repeat BOOLEAN NOT NULL, selection_weight INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL,
    UNIQUE (role_id, level_id, topic_id)
);
CREATE INDEX idx_interview_catalog_rules_role_level ON interview_catalog_rules(role_id, level_id);

